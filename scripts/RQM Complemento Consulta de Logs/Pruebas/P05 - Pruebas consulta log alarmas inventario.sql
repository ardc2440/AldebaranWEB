SET NOCOUNT ON;
DECLARE @r TABLE (PRUEBA VARCHAR(80), RESULTADO NVARCHAR(300), OK BIT);
DECLARE @From DATE = (SELECT CAST(MIN(EVENT_DATE) AS DATE) FROM INVENTORY_ALARM_LOG), @To DATE = CAST(GETDATE() AS DATE);
DECLARE @t TABLE (INVENTORY_ALARM_LOG_ID INT, EVENT_DATE DATETIME, ALARM_TYPE_CODE VARCHAR(30), ALARM_TYPE_NAME NVARCHAR(100), ALARM_ID INT, REFERENCE_ID INT,
                  REFERENCE_DESCRIPTION NVARCHAR(400), EVENT_TYPE CHAR(1), PREVIOUS_QUANTITY INT, NEW_QUANTITY INT, PREVIOUS_MINIMUM_QUANTITY INT, NEW_MINIMUM_QUANTITY INT,
                  PREVIOUS_CREATION_DATE DATETIME, NEW_CREATION_DATE DATETIME, INACTIVATION_DATE DATETIME, VISUALIZATION_COUNT INT, VISUALIZATIONS_REMOVED BIT, SOURCE VARCHAR(60), TOTAL_ROWS INT);
DECLARE @total INT, @esperado INT;

/* L1: total sin filtros = COUNT(*) directo */
INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, NULL, NULL, NULL, 0, 5;
SELECT @total = MAX(TOTAL_ROWS) FROM @t;
SELECT @esperado = COUNT(*) FROM INVENTORY_ALARM_LOG WHERE EVENT_DATE >= @From AND EVENT_DATE < DATEADD(DAY, 1, CAST(@To AS DATETIME));
INSERT @r SELECT 'L1 Total sin filtros = COUNT(*)', CONCAT(@total, N' vs ', @esperado), CASE WHEN @total = @esperado AND (SELECT COUNT(*) FROM @t) <= 5 THEN 1 ELSE 0 END;

/* L2: filtro por tipo de evento I */
DELETE @t; INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, NULL, 'I', NULL, 0, 500;
SELECT @esperado = COUNT(*) FROM INVENTORY_ALARM_LOG WHERE EVENT_TYPE = 'I' AND EVENT_DATE >= @From AND EVENT_DATE < DATEADD(DAY, 1, CAST(@To AS DATETIME));
INSERT @r SELECT 'L2 Filtro inactivaciones', CONCAT(ISNULL(MAX(TOTAL_ROWS), 0), N' vs ', @esperado), CASE WHEN ISNULL(MAX(TOTAL_ROWS), 0) = @esperado AND NOT EXISTS (SELECT 1 FROM @t WHERE EVENT_TYPE <> 'I') THEN 1 ELSE 0 END FROM @t;

/* L3: filtro por tipo de alarma */
DELETE @t; INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, 'MINIMUM_QUANTITY', NULL, NULL, 0, 500;
INSERT @r SELECT 'L3 Filtro tipo MINIMUM_QUANTITY', CONCAT(COUNT(*), N' filas'), CASE WHEN NOT EXISTS (SELECT 1 FROM @t WHERE ALARM_TYPE_CODE <> 'MINIMUM_QUANTITY') THEN 1 ELSE 0 END FROM @t;

/* L4: búsqueda por referencia u origen */
DELETE @t; INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, NULL, NULL, N'Movimiento', 0, 500;
INSERT @r SELECT 'L4 Búsqueda por texto', CONCAT(COUNT(*), N' filas'), CASE WHEN NOT EXISTS (SELECT 1 FROM @t WHERE REFERENCE_DESCRIPTION NOT LIKE N'%Movimiento%' AND SOURCE NOT LIKE '%Movimiento%') THEN 1 ELSE 0 END FROM @t;

/* L5: paginación sin solapes */
DECLARE @p1 TABLE (ID INT);
DECLARE @p2 TABLE (ID INT);
DELETE @t; INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, NULL, NULL, NULL, 0, 2;  INSERT @p1 SELECT INVENTORY_ALARM_LOG_ID FROM @t;
DELETE @t; INSERT @t EXEC SP_GET_INVENTORY_ALARM_LOG @From, @To, NULL, NULL, NULL, 2, 2;  INSERT @p2 SELECT INVENTORY_ALARM_LOG_ID FROM @t;
INSERT @r SELECT 'L5 Paginación sin solapes', CONCAT((SELECT COUNT(*) FROM @p1), N' + ', (SELECT COUNT(*) FROM @p2)), CASE WHEN NOT EXISTS (SELECT 1 FROM @p1 a JOIN @p2 b ON b.ID = a.ID) THEN 1 ELSE 0 END;

/* L6: rango obligatorio */
BEGIN TRY
    EXEC SP_GET_INVENTORY_ALARM_LOG NULL, @To;
    INSERT @r VALUES ('L6 Rango obligatorio (error 50002)', N'No lanzó error', 0);
END TRY
BEGIN CATCH
    INSERT @r VALUES ('L6 Rango obligatorio (error 50002)', CONCAT(ERROR_NUMBER(), N': ', ERROR_MESSAGE()), CASE WHEN ERROR_NUMBER() = 50002 THEN 1 ELSE 0 END);
END CATCH

SELECT * FROM @r;

   RQM Complemento Consulta de Logs - T4: Pruebas de SP_GET_INVENTORY_ALARM_LOG
   Ejecutar después de "Despliegue\06 - Consulta log alarmas inventario.sql". Solo lectura.
   Revisar la columna OK (1 = pasa).

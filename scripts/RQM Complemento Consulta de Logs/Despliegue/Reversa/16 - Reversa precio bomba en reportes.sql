/* Reversa T20/T21/T22: restaura las definiciones originales de los SP de reportes desde RQM_LOGS_OBJECT_BACKUP. */
SET NOCOUNT ON;
GO
DECLARE @n SYSNAME, @d NVARCHAR(MAX);
DECLARE c CURSOR LOCAL FOR
    SELECT OBJECT_NAME, DEFINITION FROM dbo.RQM_LOGS_OBJECT_BACKUP
     WHERE OBJECT_NAME IN ('SP_GET_ITEM_REFERENCES_REPORT', 'SP_GET_MINIMUM_WAREHOUSE_STOCK_REPORT');
OPEN c; FETCH c INTO @n, @d;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @d = STUFF(@d, PATINDEX('%CREATE%PROCEDURE%', @d), CHARINDEX('PROCEDURE', @d) - PATINDEX('%CREATE%PROCEDURE%', @d), 'ALTER ');
    EXEC sys.sp_executesql @d;
    FETCH c INTO @n, @d;
END
CLOSE c; DEALLOCATE c;
GO

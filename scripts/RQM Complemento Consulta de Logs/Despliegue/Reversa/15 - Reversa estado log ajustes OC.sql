/* Reversa T18 (deuda 4): devuelve el estado original del log de aprobaciones de ajustes de OC
   desde RQM_LOGS_PO_ADJUSTMENT_STATUS_BACKUP. Ejecutar solo si se reversa también el cambio de código. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
GO

IF OBJECT_ID('dbo.RQM_LOGS_PO_ADJUSTMENT_STATUS_BACKUP') IS NOT NULL
BEGIN
    BEGIN TRAN;
        UPDATE l
           SET NEW_STATUS_DOCUMENT_TYPE_ID = b.PREVIOUS_STATUS_DOCUMENT_TYPE_ID
          FROM dbo.PURCHASE_ORDER_ADJUSTMENT_LOG l
          JOIN dbo.RQM_LOGS_PO_ADJUSTMENT_STATUS_BACKUP b ON b.PURCHASE_ORDER_ADJUSTMENT_LOG_ID = l.PURCHASE_ORDER_ADJUSTMENT_LOG_ID;
        DROP TABLE dbo.RQM_LOGS_PO_ADJUSTMENT_STATUS_BACKUP;
    COMMIT;
END
GO
